// ===== ESTADO GLOBAL =====
let currentLang = localStorage.getItem("lang") || "pt";
let typedInstance = null;

// ===== INICIALIZAÇÃO =====
document.addEventListener("DOMContentLoaded", function () {
  applyLang(currentLang);
});

// ===== TROCAR IDIOMA =====
function toggleLang() {
  currentLang = currentLang === "pt" ? "en" : "pt";
  localStorage.setItem("lang", currentLang);
  applyLang(currentLang);
}

// ===== APLICAR IDIOMA =====
function applyLang(lang) {
  const dict = translations[lang];

  // Atualizar botão
  const btn = document.getElementById("btn-lang");
  if (lang === "pt") {
    btn.textContent = "🇺🇸 EN";
  } else {
    btn.textContent = "🇧🇷 PT";
  }

  // Atualizar atributo lang do HTML
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";

  // Atualizar textos via data-i18n (innerHTML para suportar <strong>)
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Atualizar o prefixo do hero (e eu sou / and I'm a)
  document.querySelectorAll("[data-i18n-prefix]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-prefix");
    if (dict[key]) {
      // Preservar o <span class="text"> dentro
      var span = el.querySelector(".text");
      el.innerHTML = dict[key];
      if (span) {
        el.appendChild(span);
      } else {
        var newSpan = document.createElement("span");
        newSpan.className = "text";
        el.appendChild(newSpan);
      }
    }
  });

  // Atualizar placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Reiniciar Typed.js com as frases do idioma correto
  initTyped(lang);
}

// ===== TYPED.JS =====
function initTyped(lang) {
  // Destruir instância anterior se existir
  if (typedInstance) {
    typedInstance.destroy();
  }

  typedInstance = new Typed(".text", {
    strings: typedStrings[lang],
    typeSpeed: 40,
    backSpeed: 20,
    backDelay: 1200,
    smartBackspace: true,
    loop: true
  });
}

// ===== ENVIAR CONTATO (FormSubmit.co) =====
function enviarContato(event) {
  event.preventDefault();

  const nome = document.getElementById("nome").value;
  const email = document.getElementById("email").value;
  const telefone = document.getElementById("telefone").value;
  const mensagem = document.getElementById("mensagem").value;
  const btnEnviar = document.querySelector(".btn-enviar");

  // Desabilitar botão enquanto envia
  btnEnviar.disabled = true;
  btnEnviar.textContent = currentLang === "pt" ? "Enviando..." : "Sending...";

  const formData = {
    name: nome,
    email: email,
    phone: telefone,
    message: mensagem,
    _subject: `Contato via Portfólio - ${nome}`,
    _captcha: "false",
    _template: "table"
  };

  fetch("https://formsubmit.co/ajax/polly4dev@gmail.com", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Accept": "application/json"
    },
    body: JSON.stringify(formData)
  })
    .then(function (response) {
      if (response.ok) {
        return response.json();
      }
      throw new Error("Erro no envio");
    })
    .then(function () {
      // Limpar formulário e mostrar modal de sucesso
      document.querySelector(".form-contato").reset();
      abrirModal();
    })
    .catch(function () {
      // Modal de erro
      document.getElementById("modal-titulo").textContent =
        currentLang === "pt" ? "Erro no envio" : "Send Error";
      document.getElementById("modal-texto").textContent =
        currentLang === "pt"
          ? "Não foi possível enviar a mensagem. Tente novamente mais tarde."
          : "Could not send the message. Please try again later.";
      document.querySelector(".modal-icon").textContent = "❌";
      abrirModal();
    })
    .finally(function () {
      btnEnviar.disabled = false;
      btnEnviar.textContent = translations[currentLang]["contact-btn"];
    });
}

// ===== MODAL =====
function abrirModal() {
  document.getElementById("modal-sucesso").classList.add("ativo");
}

function fecharModal() {
  const modal = document.getElementById("modal-sucesso");
  modal.classList.remove("ativo");
  // Restaurar conteúdo padrão do modal
  document.querySelector(".modal-icon").textContent = "✅";
  document.getElementById("modal-titulo").textContent = translations[currentLang]["modal-title"];
  document.getElementById("modal-texto").textContent = translations[currentLang]["modal-text"];
}
